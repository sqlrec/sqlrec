#!/usr/bin/env bash
# Fixed Bash orchestration; setup, data contracts and public workflows use CLIs.
set -euo pipefail

script_dir="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)"
repo_root="$(cd -- "$script_dir/../.." && pwd -P)"
invocation_dir="$PWD"
python_bin="${PYTHON_BIN:-$repo_root/.venv/bin/python}"
mode=all
configs=()
config_count=0
output_root="$script_dir/runs"
profile=smoke
run_id=
upload=1
provision=1
require_formal=0
workflow_options=0

usage() {
  cat <<'USAGE'
Usage: run_tests.sh [all|unit|quality] [options]

Modes:
  all        Automatic setup, local tests, then all 10 quality configs (default).
  unit       Automatic Python dependencies and local tests; no deployment/data setup.
  quality    Automatic environment/data setup, then all 10 quality configs.

Options for quality/all:
  --config FILE             Replace the fixed suite; repeat for several configs.
  --profile smoke|full      Smoke samples workflow inputs (default); full uses all prepared data.
  --run-id ID               Unique 1-32 lowercase/digit/underscore suffix; generated by default.
  --output DIR              DIR/<run-id>/ contains logs, setup.json and summary.md.
  --skip-upload             Resolved training data must already be in shared storage.
  --skip-provision-index    Matching empty collections must already exist.
  --require-formal          Require verified workflow/runtime/resource conformance.
  -h, --help                Show help without setup or execution.

Environment:
  PYTHON_BIN                Optional existing Python; otherwise create/reuse repository .venv.
  BENCH_DATA_ROOT           Cache root (default: benchmark/model_quality/data).
  BENCH_FS_URI              Shared filesystem, otherwise Hadoop fs.defaultFS.
  BENCH_STORAGE_ROOT        Optional shared training root.
  BENCH_MODEL_BASE_URI      Optional public model-artifact root.
  BENCH_TRAIN_CPU/MEMORY    Training defaults: 2 / 4Gi.
  BENCH_SERVICE_CPU/MEMORY  Serving defaults: 1 / 2Gi.
  BENCH_TZREC_VERSION       Image version, otherwise SQLREC_VERSION-cpu.
  BENCH_GBDT_VERSION        Image version, otherwise SQLREC_VERSION-cpu.
  SQLREC_BENCH_MILVUS_TOKEN Optional credential; empty for unauthenticated Milvus.

Run from any directory. Config/output arguments are relative to invocation directory;
dataset paths are relative to repository root. Python 3 and an existing SQLRec deployment
are prerequisites. Dependencies, downloads, preparation and caching are automatic.
Each model runs once with seed 123 by default. Deployment upgrades and uncertain
mutation retries are not automatic. Existing suite paths are never overwritten.
USAGE
}
die() { printf 'Error: %s\n' "$*" >&2; exit 2; }
absolute_argument() {
  case "$1" in /*) printf '%s\n' "$1" ;; *) printf '%s/%s\n' "$invocation_dir" "$1" ;; esac
}
if [[ $# -gt 0 ]]; then
  case "$1" in unit|quality|all) mode="$1"; shift ;; esac
fi
while [[ $# -gt 0 ]]; do
  case "$1" in
    --config|--output|--profile|--run-id)
      [[ $# -ge 2 && -n "$2" && "$2" != --* ]] || die "$1 requires a value"
      case "$1" in
        --config) configs+=("$(absolute_argument "$2")"); config_count=$((config_count + 1)) ;;
        --output) output_root="$(absolute_argument "$2")" ;;
        --profile) profile="$2" ;;
        --run-id) run_id="$2" ;;
      esac
      workflow_options=1; shift 2 ;;
    --skip-upload) upload=0; workflow_options=1; shift ;;
    --skip-provision-index) provision=0; workflow_options=1; shift ;;
    --require-formal) require_formal=1; workflow_options=1; shift ;;
    -h|--help) usage; exit 0 ;;
    *) die "unknown argument: $1" ;;
  esac
done
[[ "$mode" != unit || "$workflow_options" == 0 ]] || die 'workflow options require quality or all mode'
[[ "$profile" == smoke || "$profile" == full ]] || die 'profile must be smoke or full'
if [[ "$mode" != unit && "$config_count" == 0 ]]; then
  configs=(
    "$script_dir/configs/movielens100k_recall.yaml"
    "$script_dir/configs/kuairand_recall.yaml"
    "$script_dir/configs/kuairec_recall.yaml"
    "$script_dir/configs/movielens100k_ranking.yaml"
    "$script_dir/configs/movielens100k_trees.yaml"
    "$script_dir/configs/kuairand_ranking.yaml"
    "$script_dir/configs/kuairand_trees.yaml"
    "$script_dir/configs/kuairand_multitask.yaml"
    "$script_dir/configs/kuairec_ranking.yaml"
    "$script_dir/configs/kuairec_trees.yaml"
  )
  config_count="${#configs[@]}"
fi
run_id="${run_id:-$(date -u +%Y%m%d_%H%M%S)_$$}"
[[ "$run_id" =~ ^[a-z0-9_]{1,32}$ ]] || die 'invalid run-id'
suite_root="$output_root/$run_id"
[[ ! -e "$suite_root" ]] || die "run already exists: $suite_root"
run_dirs=()
for ((i = 0; i < config_count; i++)); do
  filename="${configs[i]##*/}"
  run_dir="$suite_root/${filename%.*}"
  for previous in "${run_dirs[@]:-}"; do
    [[ "$run_dir" != "$previous" ]] || die "duplicate config filename: $filename"
  done
  run_dirs+=("$run_dir")
done
# Normalize a relative explicit interpreter before changing the working directory.
if [[ "$python_bin" == */* && "$python_bin" != /* ]]; then
  python_bin="$(absolute_argument "$python_bin")"
fi
bootstrap_python="$(command -v "$python_bin" || command -v python3 || true)"
[[ -n "$bootstrap_python" ]] || die 'Python 3 is required to bootstrap the test environment'
cd -- "$repo_root"
mkdir -p -- "$suite_root/logs"
bootstrap_cli=("$bootstrap_python" -m benchmark.model_quality.bootstrap)
if [[ "$config_count" -gt 0 ]]; then
  "${bootstrap_cli[@]}" init --run "$suite_root" --inputs "${run_dirs[@]}"
else
  "${bootstrap_cli[@]}" init --run "$suite_root"
fi
active_run=
active_pid=
cleanup_blocked=0
workflow_cli=()

cleanup_active() {
  [[ -n "$active_run" && -f "$active_run/resolved_plan.json" ]] || return 0
  run_command "${workflow_cli[@]}" cleanup-services --run "$active_run" >> "$suite_root/logs/cleanup.log" 2>&1
}
on_signal() {
  local code="$1"
  trap '' INT TERM
  if [[ -n "$active_pid" ]]; then
    kill -TERM "$active_pid" 2>/dev/null || true
    wait "$active_pid" || true
    active_pid=
  fi
  exit "$code"
}
on_exit() {
  local code="$?"
  trap - EXIT INT TERM
  if ! cleanup_active; then
    printf 'Resource release is unproven: %s. Scheduling is blocked.\n' "$active_run" >&2
    code=1
  fi
  "${bootstrap_cli[@]}" finalize --run "$suite_root" --exit-code "$code" || code=1
  exit "$code"
}
trap on_exit EXIT
trap 'on_signal 130' INT
trap 'on_signal 143' TERM

run_command() {
  local status=0
  "$@" &
  active_pid=$!
  wait "$active_pid" || status=$?
  active_pid=
  return "$status"
}

run_stage() {
  local name="$1" status=0 log
  shift
  log="$suite_root/logs/$name.log"
  "${bootstrap_cli[@]}" status --run "$suite_root" --stage "$name" --status running --message "logs/$name.log"
  printf '\nStage: %s\nLog: %s\n' "$name" "$log"
  run_command "$@" > >(tee -a -- "$log") 2>&1 || status=$?
  if [[ "$status" == 0 ]]; then
    "${bootstrap_cli[@]}" status --run "$suite_root" --stage "$name" --status succeeded
  else
    "${bootstrap_cli[@]}" status --run "$suite_root" --stage "$name" --status failed
    printf 'Stage failed: %s. Review %s.\n' "$name" "$log" >&2
  fi
  return "$status"
}
# The source operation must run in this shell so deployment exports remain available.
if [[ "$mode" != unit ]]; then
  "${bootstrap_cli[@]}" status --run "$suite_root" --stage deployment_env --status running --message logs/deployment_env.log
  set +u
  if source "$repo_root/deploy/env.sh" > >(tee -a -- "$suite_root/logs/deployment_env.log") 2>&1; then
    set -u
    "${bootstrap_cli[@]}" status --run "$suite_root" --stage deployment_env --status succeeded
  else
    set -u
    "${bootstrap_cli[@]}" status --run "$suite_root" --stage deployment_env --status failed
    die 'could not load deploy/env.sh; review logs/deployment_env.log'
  fi
  export SQLREC_BENCH_MILVUS_TOKEN="${SQLREC_BENCH_MILVUS_TOKEN-}"
fi
if ! command -v "$python_bin" >/dev/null 2>&1; then
  [[ -z "${PYTHON_BIN:-}" ]] || die "PYTHON_BIN executable not found: $python_bin"
  run_stage python_env "$bootstrap_python" -m venv "$repo_root/.venv" || exit 1
fi
run_stage dependencies "$python_bin" -m benchmark.model_quality.bootstrap dependencies \
  --run "$suite_root" --requirements "$script_dir/requirements.txt" || exit 1
workflow_cli=("$python_bin" -m benchmark.model_quality.sql_workflow)
if [[ "$mode" == unit || "$mode" == all ]]; then
  run_stage unit_tests "$python_bin" -m unittest discover -s benchmark/model_quality/tests -v || exit 1
fi
[[ "$mode" != unit ]] || exit 0
run_stage preflight "${workflow_cli[@]}" preflight --run "$suite_root" \
  --inputs "${configs[@]}" --profile "$profile" --run-id "$run_id" || exit 1
run_stage prepare_data "${workflow_cli[@]}" prepare-data --run "$suite_root" \
  --inputs "${configs[@]}" --profile "$profile" --run-id "$run_id" || exit 1

run_workflow() {
  local config="$1" run_dir="$2" workflow_status=0
  run_command "${workflow_cli[@]}" build --config "$config" --run "$run_dir" --profile "$profile" --run-id "$run_id" \
    --prepared-inputs "$suite_root/prepared_inputs.json" || return "$?"
  if [[ "$upload" == 1 ]]; then
    run_command "${workflow_cli[@]}" upload-data --run "$run_dir" || workflow_status=$?
  fi
  if [[ "$workflow_status" == 0 && "$provision" == 1 ]]; then
    run_command "${workflow_cli[@]}" provision-index --run "$run_dir" || workflow_status=$?
  fi
  if [[ "$workflow_status" == 0 ]]; then
    run_command "${workflow_cli[@]}" run --run "$run_dir" || workflow_status=$?
  fi
  if ! cleanup_active; then
    cleanup_blocked=1; workflow_status=1
  fi
  if [[ "$workflow_status" == 0 ]]; then
    if [[ "$require_formal" == 1 ]]; then
      run_command "${workflow_cli[@]}" evaluate --run "$run_dir" --require-formal || workflow_status=$?
    else
      run_command "${workflow_cli[@]}" evaluate --run "$run_dir" || workflow_status=$?
    fi
  elif [[ -f "$run_dir/execution/journal.json" ]]; then
    run_command "${workflow_cli[@]}" evaluate --run "$run_dir" --diagnostic || true
  fi
  return "$workflow_status"
}

failures=0
summary_args=()
for ((i = 0; i < config_count; i++)); do
  printf '\nRunning config: %s\nOutput: %s\n' "${configs[i]}" "${run_dirs[i]}"
  active_run="${run_dirs[i]}"
  # Keep orchestration in this shell: cleanup_blocked must survive command completion.
  stage_name="${active_run##*/}"
  "${bootstrap_cli[@]}" status --run "$suite_root" --stage "$stage_name" --status running --message "logs/$stage_name.log"
  if run_workflow "${configs[i]}" "${run_dirs[i]}" > >(tee -a -- "$suite_root/logs/$stage_name.log") 2>&1; then
    "${bootstrap_cli[@]}" status --run "$suite_root" --stage "$stage_name" --status succeeded
  else
    failures=$((failures + 1)); summary_args+=(--failed-run "${run_dirs[i]}")
    "${bootstrap_cli[@]}" status --run "$suite_root" --stage "$stage_name" --status failed
  fi
  if [[ "$cleanup_blocked" == 1 ]]; then
    printf 'Stopping suite: resources are not confirmed released.\n' >&2
    for ((j = i + 1; j < config_count; j++)); do
      summary_args+=(--not-executed "${run_dirs[j]}")
    done
    break
  fi
  active_run=
done
if [[ "$failures" -gt 0 ]]; then
  run_stage summarize "${workflow_cli[@]}" summarize --run "$suite_root" --inputs "${run_dirs[@]}" "${summary_args[@]}" || exit 1
else
  run_stage summarize "${workflow_cli[@]}" summarize --run "$suite_root" --inputs "${run_dirs[@]}" || exit 1
fi
[[ "$failures" -eq 0 ]]
